// Generates data.js for the look prototype: picture cells and smooth shapes from the game.
// Run: node prototypes/snake/look/data.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../../../src/games/snake/pictures/', import.meta.url);
const { LIBRARY } = await import(new URL('library.ts', root).href);
const { parsePicture } = await import(new URL('parse.ts', root).href);
const { strokeShape } = await import(new URL('smooth.ts', root).href);

const out = {};
for (const src of LIBRARY) {
	const pic = parsePicture(src, 24, 14);
	out[pic.id] = {
		hue: pic.hue,
		cycles: pic.cycles,
		strokes: pic.strokes.map((s) => {
			const sh = strokeShape(s);
			const r = (p) => [+p.x.toFixed(3), +p.y.toFixed(3)];
			return { cells: s.cells.map((c) => [c.x, c.y]), smooth: sh.smooth.map(r) };
		})
	};
}
const file = fileURLToPath(new URL('data.js', import.meta.url));
writeFileSync(file, `// Generated by data.mjs — do not edit.\nwindow.PICTURES = ${JSON.stringify(out)};\n`);
console.log('wrote', file);
